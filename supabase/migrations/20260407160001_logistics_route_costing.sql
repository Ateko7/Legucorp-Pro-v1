  organization_id uuid not null,
  ruta_id uuid not null,
  order_id uuid not null,
  client_id uuid,
  sequence_no integer not null check (sequence_no > 0),
  status text not null default 'pendiente'
    check (status in ('pendiente', 'en_camino', 'entregado', 'parcial', 'omitido')),
  client_name_snapshot text not null,
  delivery_address_snapshot text not null,
  delivery_latitude numeric(10,7),
  delivery_longitude numeric(10,7),
  order_total_snapshot numeric not null default 0,
  delivery_photo_url text,
  delivery_notes text,
  dispatched_at timestamptz,
  delivered_at timestamptz,
  allocated_initial_cost numeric not null default 0,
  allocated_return_cost numeric not null default 0,
  allocated_progressive_cost numeric not null default 0,
  allocated_extra_fuel_cost numeric not null default 0,
  allocated_total_cost numeric not null default 0,
  margin_amount numeric not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
