  on public.ruta_pedidos (ruta_id, sequence_no);

create index if not exists idx_ruta_pedidos_org_status
  on public.ruta_pedidos (organization_id, status, sequence_no);

create table if not exists public.ruta_tramos (
  id uuid not null default gen_random_uuid(),
  organization_id uuid not null,
  ruta_id uuid not null,
  sequence_no integer not null check (sequence_no > 0),
  segment_kind text not null
    check (segment_kind in ('salida_planta', 'intercliente', 'retorno_planta')),
  generated_from_event text not null
    check (generated_from_event in ('inicio_ruta', 'despacho_cliente', 'retorno_ruta')),
  from_stop_type text not null check (from_stop_type in ('planta', 'cliente')),
  to_stop_type text not null check (to_stop_type in ('planta', 'cliente')),
  from_ruta_pedido_id uuid,
  to_ruta_pedido_id uuid,
  from_label text not null,
  to_label text not null,
  origin_address text,
  destination_address text,
  origin_latitude numeric(10,7),
  origin_longitude numeric(10,7),
  destination_latitude numeric(10,7),
  destination_longitude numeric(10,7),
  distance_meters integer not null default 0,
  duration_seconds integer not null default 0,
  distance_km numeric not null default 0,
  duration_minutes numeric not null default 0,
  fuel_price_per_gallon numeric not null default 0,
  vehicle_efficiency_km_per_gallon numeric not null default 0,
  estimated_gallons numeric not null default 0,
  segment_cost numeric not null default 0,
  google_maps_response jsonb,
  created_by uuid,
  created_at timestamptz not null default now(),
  constraint ruta_tramos_pkey primary key (id),
  constraint ruta_tramos_organization_id_fkey foreign key (organization_id) references public.organizations(id) on delete cascade,
  constraint ruta_tramos_ruta_id_fkey foreign key (ruta_id) references public.rutas(id) on delete cascade,
  constraint ruta_tramos_from_ruta_pedido_id_fkey foreign key (from_ruta_pedido_id) references public.ruta_pedidos(id) on delete set null,
  constraint ruta_tramos_to_ruta_pedido_id_fkey foreign key (to_ruta_pedido_id) references public.ruta_pedidos(id) on delete set null,
  constraint ruta_tramos_created_by_fkey foreign key (created_by) references public.profiles(id)
);

create unique index if not exists idx_ruta_tramos_ruta_sequence_unique
  on public.ruta_tramos (ruta_id, sequence_no);

create index if not exists idx_ruta_tramos_org_ruta
  on public.ruta_tramos (organization_id, ruta_id, created_at);

