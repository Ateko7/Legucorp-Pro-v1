  constraint ruta_pedidos_organization_id_fkey foreign key (organization_id) references public.organizations(id) on delete cascade,
  constraint ruta_pedidos_ruta_id_fkey foreign key (ruta_id) references public.rutas(id) on delete cascade,
  constraint ruta_pedidos_order_id_fkey foreign key (order_id) references public.orders(id) on delete restrict,
  constraint ruta_pedidos_client_id_fkey foreign key (client_id) references public.clients(id) on delete set null
);

create unique index if not exists idx_ruta_pedidos_ruta_order_unique
