create table if not exists public.logistics_settings (
  id uuid not null default gen_random_uuid(),
  organization_id uuid not null,
  plant_name text,
  plant_address text,
  plant_latitude numeric(10,7),
  plant_longitude numeric(10,7),
  default_currency text not null default 'GTQ',
  created_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint logistics_settings_pkey primary key (id),
  constraint logistics_settings_organization_id_fkey foreign key (organization_id) references public.organizations(id) on delete cascade,
  constraint logistics_settings_created_by_fkey foreign key (created_by) references public.profiles(id)
);

create unique index if not exists idx_logistics_settings_org_unique
  on public.logistics_settings (organization_id);

create table if not exists public.vehiculos (
  id uuid not null default gen_random_uuid(),
  organization_id uuid not null,
  code text,
  name text not null,
  plate text not null,
  fuel_type text not null
    check (fuel_type in ('diesel', 'gasolina_regular', 'gasolina_super')),
  fuel_efficiency_km_per_gallon numeric not null default 0
    check (fuel_efficiency_km_per_gallon > 0),
  tank_capacity_gallons numeric,
  is_active boolean not null default true,
  notes text,
  created_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint vehiculos_pkey primary key (id),
  constraint vehiculos_organization_id_fkey foreign key (organization_id) references public.organizations(id) on delete cascade,
  constraint vehiculos_created_by_fkey foreign key (created_by) references public.profiles(id)
);

create unique index if not exists idx_vehiculos_org_plate_unique
  on public.vehiculos (organization_id, plate);

create index if not exists idx_vehiculos_org_active
  on public.vehiculos (organization_id, is_active, name);

create table if not exists public.historial_combustible (
  id uuid not null default gen_random_uuid(),
