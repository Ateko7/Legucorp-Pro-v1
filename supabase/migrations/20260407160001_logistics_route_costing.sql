  constraint historial_combustible_organization_id_fkey foreign key (organization_id) references public.organizations(id) on delete cascade,
  constraint historial_combustible_created_by_fkey foreign key (created_by) references public.profiles(id)
);

create index if not exists idx_historial_combustible_org_type_date
  on public.historial_combustible (organization_id, fuel_type, effective_date desc, created_at desc);

create table if not exists public.rutas (
  id uuid not null default gen_random_uuid(),
  organization_id uuid not null,
  route_number bigint generated by default as identity,
  route_name text,
  route_date date not null default current_date,
  vehicle_id uuid not null,
  driver_name text,
  driver_phone text,
  status text not null default 'planificada'
    check (status in ('planificada', 'en_ruta', 'finalizada', 'cancelada')),
  current_stop_sequence integer not null default 0,
  started_at timestamptz,
  finished_at timestamptz,
  plant_name_snapshot text,
  plant_address_snapshot text,
  plant_latitude numeric(10,7),
  plant_longitude numeric(10,7),
  notes text,
  total_orders integer not null default 0,
  total_distance_km numeric not null default 0,
  total_duration_minutes numeric not null default 0,
  total_segment_cost numeric not null default 0,
  total_extra_fuel_cost numeric not null default 0,
  total_route_cost numeric not null default 0,
  created_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint rutas_pkey primary key (id),
  constraint rutas_organization_id_fkey foreign key (organization_id) references public.organizations(id) on delete cascade,
  constraint rutas_vehicle_id_fkey foreign key (vehicle_id) references public.vehiculos(id),
  constraint rutas_created_by_fkey foreign key (created_by) references public.profiles(id)
);

create unique index if not exists idx_rutas_org_route_number
  on public.rutas (organization_id, route_number);

create index if not exists idx_rutas_org_status_date
  on public.rutas (organization_id, status, route_date desc, created_at desc);

create table if not exists public.ruta_pedidos (
